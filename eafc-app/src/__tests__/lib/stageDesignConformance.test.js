const HEX_LITERAL = /#[0-9A-Fa-f]{6}\b/;
const EMOJI = /\p{Extended_Pictographic}/u;

describe('Stage design conformance', () => {
  test('RESTYLED_FILES entries all exist', () => {
    RESTYLED_FILES.forEach((file) => {
      expect(fs.existsSync(path.join(ROOT, file))).toBe(true);
    });
  });

  RESTYLED_FILES.forEach((file) => {
    const source = () => fs.readFileSync(path.join(ROOT, file), 'utf8');

    test(`${file} has no hex colour literals`, () => {
      expect(source()).not.toMatch(HEX_LITERAL);
    });

    test(`${file} has no emoji`, () => {
      expect(source()).not.toMatch(EMOJI);
    });
  });
});
